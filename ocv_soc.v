`timescale 1ns / 1ps

// ================================================================
// Project 1: Lithium-Ion Battery Modeling & SOC Estimation
// Module   : ocv_soc
// Method   : OCV-based SOC estimation
// Tool     : Xilinx Vivado
//
// Input:
//   OCV voltage in mV
//
// Output:
//   SOC = 0 to 10000
//   10000 = 100.00%
//    5000 = 50.00%
//       0 = 0.00%
//
// Approximate Li-ion OCV-SOC characteristic:
//
//   OCV       SOC
//   4.20 V    100%
//   4.10 V     90%
//   4.05 V     80%
//   4.00 V     70%
//   3.95 V     60%
//   3.90 V     50%
//   3.85 V     40%
//   3.80 V     30%
//   3.75 V     20%
//   3.65 V     10%
//   3.00 V      0%
//
// NOTE:
// This is an educational approximate Li-ion curve.
// A real battery should use experimentally measured OCV-SOC
// data for accurate estimation.
// ================================================================

module ocv_soc (

    input  wire [15:0] ocv_mv,

    output reg [13:0] soc_ocv

);

    // ------------------------------------------------------------
    // OCV ? SOC lookup
    //
    // Linear interpolation is not used in this first version.
    // The closest SOC region is selected using thresholds.
    // ------------------------------------------------------------

    always @(*) begin

        // --------------------------------------------------------
        // 4.20 V and above
        // --------------------------------------------------------

        if (ocv_mv >= 16'd4200)

            soc_ocv = 14'd10000;

        // --------------------------------------------------------
        // 4.10 V - 4.20 V
        // --------------------------------------------------------

        else if (ocv_mv >= 16'd4100)

            soc_ocv = 14'd9000;

        // --------------------------------------------------------
        // 4.05 V - 4.10 V
        // --------------------------------------------------------

        else if (ocv_mv >= 16'd4050)

            soc_ocv = 14'd8000;

        // --------------------------------------------------------
        // 4.00 V - 4.05 V
        // --------------------------------------------------------

        else if (ocv_mv >= 16'd4000)

            soc_ocv = 14'd7000;

        // --------------------------------------------------------
        // 3.95 V - 4.00 V
        // --------------------------------------------------------

        else if (ocv_mv >= 16'd3950)

            soc_ocv = 14'd6000;

        // --------------------------------------------------------
        // 3.90 V - 3.95 V
        // --------------------------------------------------------

        else if (ocv_mv >= 16'd3900)

            soc_ocv = 14'd5000;

        // --------------------------------------------------------
        // 3.85 V - 3.90 V
        // --------------------------------------------------------

        else if (ocv_mv >= 16'd3850)

            soc_ocv = 14'd4000;

        // --------------------------------------------------------
        // 3.80 V - 3.85 V
        // --------------------------------------------------------

        else if (ocv_mv >= 16'd3800)

            soc_ocv = 14'd3000;

        // --------------------------------------------------------
        // 3.75 V - 3.80 V
        // --------------------------------------------------------

        else if (ocv_mv >= 16'd3750)

            soc_ocv = 14'd2000;

        // --------------------------------------------------------
        // 3.65 V - 3.75 V
        // --------------------------------------------------------

        else if (ocv_mv >= 16'd3650)

            soc_ocv = 14'd1000;

        // --------------------------------------------------------
        // Below 3.65 V
        // --------------------------------------------------------

        else

            soc_ocv = 14'd0;

    end

endmodule